import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { canonicalJson } from "@promisory/domain";

const header = `// Generated by scripts/configure-development.ts from the declared capability.
// Run npm run manifest:configure to change the build and manifest together.
`;

export function forgeBuildConfig(remoteEnabled: boolean) {
  return {
    binding:
      header +
      (remoteEnabled
        ? 'export { configuredExecutor } from "../optional/remote";\n'
        : `import { UnconfiguredExecutor } from "@promisory/domain";

export async function configuredExecutor() {
  return new UnconfiguredExecutor();
}
`),
    tsconfig: {
      extends: "../../tsconfig.json",
      compilerOptions: {
        noEmit: false,
        module: "ESNext",
        moduleResolution: "Bundler",
        target: "ES2023",
      },
      include: ["src/**/*.ts", ...(remoteEnabled ? ["optional/**/*.ts"] : [])],
      exclude: [
        "node_modules",
        "static",
        "dist",
        ...(!remoteEnabled ? ["optional"] : []),
      ],
    },
  };
}

export async function writeForgeBuildConfig(
  appDirectory: string,
  remoteEnabled: boolean,
) {
  const config = forgeBuildConfig(remoteEnabled);
  await writeFile(join(appDirectory, "src/remote.ts"), config.binding);
  await writeFile(
    join(appDirectory, "tsconfig.json"),
    JSON.stringify(config.tsconfig, null, 2) + "\n",
  );
}

export async function assertForgeBuildConfig(
  appDirectory: string,
  remoteEnabled: boolean,
) {
  const expected = forgeBuildConfig(remoteEnabled);
  const [binding, tsconfig] = await Promise.all([
    readFile(join(appDirectory, "src/remote.ts"), "utf8"),
    readFile(join(appDirectory, "tsconfig.json"), "utf8"),
  ]);
  if (
    binding.trim() !== expected.binding.trim() ||
    canonicalJson(JSON.parse(tsconfig)) !== canonicalJson(expected.tsconfig)
  ) {
    throw new Error(
      "Forge executor build and declared remote capability differ. Run npm run manifest:configure for the intended executor capability before building or deploying.",
    );
  }
}
